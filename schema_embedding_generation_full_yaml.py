"""schema_embedding_generation_updated.py

Purpose
-------
Create a Chroma vector store from a YAML database schema so an LLM can:
1) retrieve relevant schema fragments via similarity search, then
2) generate correct SQL for the underlying SQLite database.

This version is tailored for the generated schema format in data/financial_model_schema.yaml.
It is also resilient to schema variations (missing/extra keys, wrapper roots, etc.).

Key improvements vs original script
----------------------------------
- No assumption of a single top-level YAML key.
- Builds *task-optimized* chunks: contract, tables, joins, sheets, concepts, SQL templates, glossary.
- Adds *metadata per chunk* (doc_type, table_name, sheet_slug, concept, template_name) to allow
  metadata-filtered retrieval in Chroma.
- Token-aware chunking using a HuggingFace tokenizer (same approach as your original).

Run
---
python schema_embedding_generation_updated.py \
  --schema data/financial_model_schema.yaml \
  --persist ./vector_stores/schema_store
"""

from __future__ import annotations

import argparse
from typing import Any, Dict, List, Tuple

import yaml
from transformers import AutoTokenizer

from langchain_huggingface import HuggingFaceEmbeddings
from langchain_community.vectorstores import Chroma

# Prefer the user's existing splitter import path, but fall back to the newer package if needed.
try:
    from langchain_classic.text_splitter import RecursiveCharacterTextSplitter  # type: ignore
except Exception:  # pragma: no cover
    from langchain_text_splitters import RecursiveCharacterTextSplitter  # type: ignore


DEFAULT_TOKENIZER_PATH = "./models/qwen_tokenizer"
DEFAULT_PERSIST_DIRECTORY = "./vector_stores/schema_store"
DEFAULT_EMBEDDING_MODEL = "sentence-transformers/all-MiniLM-L6-v2"


def _as_root(data: Any) -> Dict[str, Any]:
    """Return the schema root dict.

    Supports both:
    - root dict with keys like schema_name/tables/db, and
    - wrapper style: {<top_key>: { ...root... }}
    """
    if isinstance(data, dict):
        if "schema_name" in data or "tables" in data or "db" in data:
            return data
        if len(data) == 1:
            k = next(iter(data.keys()))
            if isinstance(data.get(k), dict):
                return data[k]
    return {}


def _safe_list(x: Any) -> List[Any]:
    return x if isinstance(x, list) else []


def _safe_dict(x: Any) -> Dict[str, Any]:
    return x if isinstance(x, dict) else {}


def _clean(x: Any) -> str:
    return "" if x is None else str(x).strip()


def _truncate(items: List[Any], n: int) -> List[Any]:
    return items[:n] if len(items) > n else items


def schema_to_chunks(
    schema_path: str,
    max_table_cols: int = 60,
    max_examples_per_col: int = 3,
) -> List[Dict[str, Any]]:
    """Convert YAML schema into a list of chunks: {text, metadata}.

    This variant is optimized for the FULL financial-model schema YAML generated by
    generate_yaml_schema.py. It focuses on the single primary
    table `facts` and embeds explicit SQL rules + playbook to prevent hallucinated
    identifiers (e.g., 'TABLE GUIDE.fact').
    """

    with open(schema_path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f)

    root = _as_root(data)

    schema_name = _clean(root.get("schema_name", "database_schema"))
    db = _safe_dict(root.get("db"))
    dialect = _clean(db.get("dialect", "sqlite"))
    db_file = _clean(db.get("file", ""))

    core_tables = _safe_dict(root.get("core_tables"))
    llm_rules = _safe_list(root.get("llm_sql_rules"))
    quick_ref = _safe_dict(root.get("quick_reference"))
    query_playbook = _safe_dict(root.get("query_playbook"))

    tables = _safe_list(root.get("tables"))

    chunks: List[Dict[str, Any]] = []

    # 1) HARD CONTRACT + CORE TABLES + RULES
    table_names = [t.get("name") for t in tables if isinstance(t, dict) and t.get("name")]
    primary_fact = _clean(core_tables.get("primary_fact_table", "facts"))
    glossary_table = _clean(core_tables.get("glossary_table", "glossary"))
    fallback_table = _clean(core_tables.get("fallback_table", "raw_cells"))
    sheet_status_table = _clean(core_tables.get("sheet_status_table", "sheet_registry"))

    contract_lines = [
        f"HARD DATABASE CONTRACT ({dialect.upper()})",
        f"Schema name: {schema_name}",
        f"Database file: {db_file}",
        "",
        "Only these tables exist:",
        *[f"- {n}" for n in table_names],
        "",
        "Core tables:",
        f"- primary_fact_table: {primary_fact}",
        f"- glossary_table: {glossary_table}",
        f"- fallback_table: {fallback_table}",
        f"- sheet_status_table: {sheet_status_table}",
        "",
        "Critical LLM SQL rules:",
        *[f"- {r}" for r in llm_rules],
        "",
        "IMPORTANT: The YAML contains headings like 'TABLE GUIDE:' and 'SHEET GUIDE:' in text chunks.",
        "Those are NOT database identifiers. Never copy them into SQL identifiers.",
    ]

    chunks.append({
        "text": "\n".join([l for l in contract_lines if l is not None]).strip(),
        "metadata": {"doc_type": "hard_contract", "schema": schema_name, "dialect": dialect}
    })

    # 2) QUICK REFERENCE chunk
    period_types = _safe_list(quick_ref.get("period_types"))
    example_sheets = _safe_list(quick_ref.get("example_sheets"))

    qr_text = "\n".join([
        "QUICK REFERENCE",
        f"- period_types: {period_types}",
        f"- example_sheets: {example_sheets}",
        "",
        "Tips:",
        "- For FY questions: WHERE period_type='FY' AND period='FY27'",
        "- For time series: WHERE period_type='DATE' ORDER BY period",
        "- Find metrics with: metric LIKE '%<keyword>%'",
        "- Prefer single-table queries on facts.",
    ]).strip()

    chunks.append({
        "text": qr_text,
        "metadata": {"doc_type": "quick_reference", "schema": schema_name}
    })

    # 3) TABLE GUIDES
    for t in tables:
        if not isinstance(t, dict):
            continue
        name = _clean(t.get("name"))
        if not name:
            continue
        desc = _clean(t.get("description"))
        row_count = t.get("row_count")
        cols = _truncate(_safe_list(t.get("columns")), max_table_cols)

        col_lines = []
        for c in cols:
            if not isinstance(c, dict):
                continue
            cn = _clean(c.get("name"))
            ct = _clean(c.get("type"))
            cdesc = _clean(c.get("description"))
            line = f"- {cn} ({ct}): {cdesc}" if cdesc else f"- {cn} ({ct})"
            col_lines.append(line)

        idx_lines = []
        for ix in _safe_list(t.get("indexes")):
            if not isinstance(ix, dict):
                continue
            idx_lines.append(f"- {ix.get('name')} (unique={ix.get('unique')}): {ix.get('columns')}")

        idx_block = idx_lines if idx_lines else ["- (none)"]
        sample = _safe_list(t.get("sample_rows"))

        table_text = "\n".join([
            f"TABLE: {name}",
            f"Purpose: {desc}",
            f"Row count: {row_count}",
            "",
            "Columns:",
            *col_lines,
            "",
            "Indexes:",
            *idx_block,
            "",
            "Sample rows:",
            *( [f"- {r}" for r in sample[:3]] if sample else ["- (none)"] ),
        ]).strip()

        chunks.append({
            "text": table_text,
            "metadata": {"doc_type": "table", "table": name, "schema": schema_name}
        })

    # 4) QUERY PLAYBOOK chunk(s)
    patterns = _safe_list(query_playbook.get("patterns"))
    troubleshooting = _safe_list(query_playbook.get("troubleshooting"))

    if patterns:
        for p in patterns:
            if not isinstance(p, dict):
                continue
            nm = _clean(p.get("name"))
            when = _clean(p.get("when"))
            sql = _clean(p.get("sql"))
            if not nm or not sql:
                continue
            chunks.append({
                "text": f"PLAYBOOK: {nm}\nWhen: {when}\nSQL example:\n{sql}",
                "metadata": {"doc_type": "playbook_pattern", "pattern": nm, "schema": schema_name}
            })

    if troubleshooting:
        chunks.append({
            "text": "TROUBLESHOOTING\n" + "\n".join([f"- {x}" for x in troubleshooting]),
            "metadata": {"doc_type": "troubleshooting", "schema": schema_name}
        })

    # de-dup while preserving order
    seen = set()
    out = []
    for ch in chunks:
        txt = _clean(ch.get("text"))
        if not txt or txt in seen:
            continue
        seen.add(txt)
        out.append(ch)
    return out


def split_chunks(
    chunks: List[Dict[str, Any]],
    chunk_size: int = 1000,
    chunk_overlap: int = 80,
    tokenizer_path: str = DEFAULT_TOKENIZER_PATH,
) -> Tuple[List[str], List[Dict[str, Any]]]:
    """Split chunk texts with token-aware splitter and propagate metadata."""

    tokenizer = AutoTokenizer.from_pretrained(tokenizer_path)
    splitter = RecursiveCharacterTextSplitter.from_huggingface_tokenizer(
        tokenizer,
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap,
    )

    out_texts: List[str] = []
    out_meta: List[Dict[str, Any]] = []

    for ch in chunks:
        text = _clean(ch.get("text"))
        meta = _safe_dict(ch.get("metadata"))
        if not text:
            continue
        parts = splitter.split_text(text)
        for i, p in enumerate(parts):
            p = _clean(p)
            if not p:
                continue
            m = dict(meta)
            m["chunk_index"] = i
            m["chunk_total"] = len(parts)
            out_texts.append(p)
            out_meta.append(m)

    # de-dup by exact text
    seen = {}
    final_texts = []
    final_meta = []
    for t, m in zip(out_texts, out_meta):
        if t in seen:
            continue
        seen[t] = True
        final_texts.append(t)
        final_meta.append(m)

    return final_texts, final_meta


def embedding_vectors(
    texts: List[str],
    metadatas: List[Dict[str, Any]],
    persist_directory: str = DEFAULT_PERSIST_DIRECTORY,
    embedding_model: str = DEFAULT_EMBEDDING_MODEL,
) -> Chroma:
    embeddings = HuggingFaceEmbeddings(model_name=embedding_model)
    store = Chroma.from_texts(
        texts=texts,
        embedding=embeddings,
        metadatas=metadatas,
        persist_directory=persist_directory,
    )
    try:
        store.persist()
    except Exception:
        pass
    return store


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--schema", required=True, help="Path to YAML schema")
    ap.add_argument("--persist", default=DEFAULT_PERSIST_DIRECTORY, help="Chroma persist directory")
    ap.add_argument("--tokenizer", default=DEFAULT_TOKENIZER_PATH, help="Tokenizer path (HF format)")
    ap.add_argument("--chunk_size", type=int, default=1000)
    ap.add_argument("--chunk_overlap", type=int, default=80)
    ap.add_argument("--embedding_model", default=DEFAULT_EMBEDDING_MODEL)
    args = ap.parse_args()

    base_chunks = schema_to_chunks(args.schema)
    texts, metas = split_chunks(
        base_chunks,
        chunk_size=args.chunk_size,
        chunk_overlap=args.chunk_overlap,
        tokenizer_path=args.tokenizer,
    )

    embedding_vectors(
        texts=texts,
        metadatas=metas,
        persist_directory=args.persist,
        embedding_model=args.embedding_model,
    )

    print(f"Embedded {len(texts)} chunks from schema: {args.schema} -> {args.persist}")


if __name__ == "__main__":
    main()
